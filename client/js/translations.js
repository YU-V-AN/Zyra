// Falls back to English, then to the raw key, so a missing translation
// never renders as "undefined" in the UI.
export function t(lang, key) {
  return (translations[lang] && translations[lang][key])
    || translations.en[key]
    || key;
}

// Walks every [data-i18n] / [data-i18n-placeholder] element in the given
// root and swaps in the translated string for the active language.
export function applyTranslations(lang, root = document) {
  root.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(lang, el.getAttribute("data-i18n"));
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.setAttribute("placeholder", t(lang, el.getAttribute("data-i18n-placeholder")));
  });
  document.documentElement.setAttribute("lang", lang);
}
